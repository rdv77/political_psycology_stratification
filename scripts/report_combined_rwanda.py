def number_points(ax,values):
    """Place short labels without obscuring each other in dense projections."""
    ax.figure.canvas.draw()
    renderer=ax.figure.canvas.get_renderer()
    occupied=[]
    candidates=[(4,4),(4,-12),(-12,4),(-14,-12),(14,1),(-22,1),(0,16),(0,-22),
                (18,16),(-24,16),(18,-24),(-26,-24),(30,0),(-34,0),(0,30),(0,-34)]
    for i,(x,y)in enumerate(values):
        label=ax.annotate(str(i+1),(x,y),xytext=(4,4),textcoords='offset points',fontsize=7)
        best=None
        for offset in candidates:
            label.set_position(offset)
            box=label.get_window_extent(renderer).expanded(1.18,1.15)
            overlap=sum(box.overlaps(other)for other in occupied)
            boundary=not ax.bbox.contains(box.x0,box.y0)or not ax.bbox.contains(box.x1,box.y1)
            cost=100*overlap+100*boundary+np.hypot(*offset)/100
            if best is None or cost<best[0]:best=(cost,offset,box)
        label.set_position(best[1]);occupied.append(best[2])
        if np.hypot(*best[1])>12:
            ax.annotate('',(x,y),xytext=best[1],textcoords='offset points',
                        arrowprops={'arrowstyle':'-','color':'#aaaaaa','lw':.4})



def inventory_rows():
    inventory_raw = (BASE / "CORPUS_HALF_PROPERTIES_RU_2026-10-17.md").read_bytes()
    # RELATIONS is a reviewed positional map: a same-length reorder is unsafe too.
    expected_sha = "712a92f9b6a204b94049f731b7e26b016e543eaae96afea98ba2e0007d1443a8"
    if hashlib.sha256(inventory_raw.replace(b"\r\n", b"\n")).hexdigest() != expected_sha:
        raise ValueError("Re-review the positional map when the frozen inventory changes")
    text = inventory_raw.decode("utf-8")
    rows = []
    family = ""
    for line in text.splitlines():
        if line.startswith("## ") and line[3:4].isdigit():
            family = line[3:]
        elif line.startswith("## "):
            family = ""
        if family and line.startswith("| ") and not line.startswith("| Предложенное название"):
            cells = [v.strip() for v in line.strip("|").split("|")]
            if len(cells) == 2:
                rows.append({"name": cells[0], "definition": cells[1], "facet_family": family})
    if len(rows) != 63 or len(RELATIONS) != 63:
        raise ValueError("Re-review consolidation when the frozen 63-row inventory changes")
    return rows


